COLORS = {
    "red":     "\033[91m",
    "green":   "\033[92m",
    "yellow":  "\033[93m",
    "blue":    "\033[94m",
    "magenta": "\033[95m",
    "cyan":    "\033[96m",
    "white":   "\033[97m",
    "reset":   "\033[0m",
}

def render(text, color="cyan", fill="#"):
    text = text.upper()
    rows = [""] * 7
    for ch in text:
        glyph = FONT.get(ch, FONT[' '])
        for i, row in enumerate(glyph):
            rows[i] += row.replace("#", fill) + " "
    c = COLORS.get(color, COLORS["cyan"])
    reset = COLORS["reset"]
    print()
    for row in rows:
        print("  " + c + row + reset)
    print()

def main():
    color_names = [k for k in COLORS if k != "reset"]
    print("\n  🎨 ASCII Art Generator")
    print(f"  Colors: {', '.join(color_names)}")
    print("  Fill chars: #  *  @  +  ░  █")
    print("  Type 'quit' to exit.\n")

    while True:
        try:
            text = input("  Text: ").strip()
            if text.lower() in ("quit", "exit", "q"):
                print("  Bye!\n")
                break
            if not text:
                continue
            color = input("  Color (default cyan): ").strip().lower() or "cyan"
            fill = input("  Fill char (default #): ").strip() or "#"
            render(text, color, fill[0])
        except KeyboardInterrupt:
            print("\n  Bye!\n")
            break

if __name__ == "__main__":
    main()
